	BYTES 0xFF, 0xFF, 0xFF, 0xE7, 0xE7, 0xE7, 0xE7, 0xFF, 0xFF, 0xFF, 0xE7, 0xE7, 0xFF, 0xFF, 0xFF

data_subtitle:
	BYTES 0xEA, 0xAE, 0xC4, 0xA4, 0xE4
	BYTES 0xAE, 0xE4, 0xE4, 0xA4, 0xAE
	BYTES 0xEE, 0x84, 0xE4, 0x24, 0xE4
